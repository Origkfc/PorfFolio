const fs=require('node:fs'),assert=require('node:assert/strict');
let clock=0;
Object.defineProperty(globalThis,'performance',{value:{now:()=>clock},configurable:true});
(async()=>{
 const source=fs.readFileSync('orbit-overdrive.js','utf8');
 const {createOrbitOverdrive}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
 function fixture(){
  const classes=new Set(),main={inert:false};let shutdowns=0;clock=0;
  globalThis.innerWidth=1280;globalThis.innerHeight=900;
  const styles=new Map();
  const words=Array.from({length:2},()=>({style:{transform:'',opacity:''},getBoundingClientRect:()=>({x:40,y:50,width:100,height:20})}));
  globalThis.getComputedStyle=()=>({visibility:'visible',opacity:'1'});
  globalThis.document={querySelector:()=>main,querySelectorAll:()=>words,body:{style:{setProperty:(k,v)=>styles.set(k,v),getPropertyValue:k=>styles.get(k),removeProperty:k=>styles.delete(k)},classList:{add:v=>classes.add(v),remove:v=>classes.delete(v)}}};
  const sound={starts:0,stops:0,elapsed:0,start(){this.starts++;},update(t){this.elapsed=t;},stop(){this.stops++;}};
  const controller=createOrbitOverdrive(()=>shutdowns++,sound);
  const state={enabled:true,reveal:1,phase:0,dimensions:[]};controller.observe(state);
  const step=(phase,options={})=>controller.observe({...state,phase,...options});
  const walk=(count,direction=1)=>{for(let i=1;i<=count;i++)step(((i*.25*direction)%3+3)%3);};
  return{controller,state,step,walk,classes,main,styles,words,sound,get shutdowns(){return shutdowns;}};
 }
 let f=fixture();f.walk(59);
 assert.equal(f.classes.has('orbit-overdrive'),false,'Less than five complete rotations must not trigger');
 f.step(0);assert.equal(f.classes.has('orbit-overdrive'),true);assert.equal(f.main.inert,true);
 assert.equal(f.shutdowns,0);clock=500;const first=f.controller.sample(f.state).phase;
 clock=1000;const second=f.controller.sample(f.state).phase;
 assert.ok(second-first>first,'Angular speed increases through the automatic spin');
 assert.equal(f.words[0].style.opacity,'1','Words wait while panels move first');
 clock=3500;const peak=f.controller.sample(f.state);assert.equal(f.shutdowns,0,'Tornado continues after 3.5 seconds');assert.equal(peak.overdrive,1);assert.ok(peak.ingest>0&&peak.ingest<1);
 assert.ok(Math.abs(parseFloat(f.styles.get('--quake-x')))<=12,'Shake amplitude stays bounded');
 assert.ok(Number(f.words[0].style.opacity)<Number(f.words[1].style.opacity),'Words join progressively rather than all at once');
 clock=4999;f.controller.sample(f.state);assert.equal(f.shutdowns,0,'No early shutdown before five seconds');
 clock=5000;const ingested=f.controller.sample(f.state);assert.equal(f.shutdowns,0,'Three more seconds of floor fracture follow ingestion');assert.equal(ingested.ingest,1);
 clock=7999;f.controller.sample(f.state);assert.equal(f.shutdowns,0,'No early shutdown before eight seconds');
 clock=8000;const end=f.controller.sample(f.state);f.controller.sample(f.state);assert.equal(f.shutdowns,1,'Shared TV shutdown is triggered once');assert.equal(end.ingest,1);assert.equal(f.sound.starts,1);assert.equal(f.sound.stops,1);
 f=fixture();f.walk(60,-1);clock=1000;assert.ok(f.controller.sample(f.state).phase<0,'Continue the user\'s reverse orbit direction');
 clock=8000;f.controller.sample(f.state);assert.equal(f.shutdowns,1);
 f=fixture();f.walk(59);clock=1001;f.controller.sample(f.state);f.step(0);f.walk(59);assert.equal(f.classes.size,0,'A one-second pause resets the entire count');f.step(0);assert.equal(f.classes.has('orbit-overdrive'),true);
 f=fixture();f.walk(59);f.step(2.5);assert.equal(f.classes.size,0,'Reversing cannot finish the prior count');for(let i=1;i<=58;i++)f.step(((2.5-i*.25)%3+3)%3);assert.equal(f.classes.size,0,'Reversed travel starts fresh');
 f=fixture();for(let i=1;i<=240;i++)f.step(i*.25,{enabled:false});assert.equal(f.classes.size,0,'Non-spatial/mobile mode never triggers');
 f=fixture();for(let i=1;i<=240;i++)f.step(i*.25,{reveal:.5});assert.equal(f.classes.size,0,'Identity-entry animation does not count');
 f=fixture();f.walk(60);f.controller.sample({...f.state,enabled:false});
 assert.equal(f.main.inert,false);assert.equal(f.classes.size,0);assert.equal(f.shutdowns,0,'Leaving desktop spatial mode cancels safely');
 assert.equal(f.words[0].style.transform,'');assert.equal(f.styles.has('--quake-x'),false,'Cancellation restores the original UI');
 f.controller.observe(f.state);assert.equal(f.classes.size,0,'Cancellation clears the old accumulated travel');
 f=fixture();f.step(2.9);f.step(.1);assert.equal(f.classes.size,0,'A wrap boundary is a short movement, not a full extra orbit');
 const app=fs.readFileSync('app.js','utf8');
 assert.ok(app.includes('orbitOverdrive.observe(spatial.sceneState)'));
 assert.ok(app.includes('getState:()=>orbitOverdrive.sample(spatial.sceneState)'));
 assert.ok(!fs.readFileSync('scene.js','utf8').includes('uStormGrowth'));
 console.log('Orbit overdrive passed: five continuous same-direction orbits, pause/reversal reset, 5s ingestion + 3s finale, sound lifecycle, single TV callback and cancellation.');
})().catch(error=>{console.error(error);process.exitCode=1;});
